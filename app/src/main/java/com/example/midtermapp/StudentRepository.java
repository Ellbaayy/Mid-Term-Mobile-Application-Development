package com.example.midtermapp;

import androidx.annotation.NonNull;
import androidx.annotation.Nullable;

import com.google.firebase.firestore.CollectionReference;
import com.google.firebase.firestore.FirebaseFirestore;
import com.google.firebase.firestore.QueryDocumentSnapshot;
import com.google.firebase.firestore.QuerySnapshot;

import java.util.ArrayList;
import java.util.Collections;
import java.util.Comparator;
import java.util.List;

/**
 * Data access layer for the student records kept in Cloud Firestore.
 *
 * Collection : Students
 * Fields     : name, studentId, enrolled
 * Document ID: generated by Firestore, so the student ID stays editable.
 */
public class StudentRepository {

    public static final String COLLECTION_STUDENTS = "Students";
    public static final String FIELD_NAME = "name";
    public static final String FIELD_STUDENT_ID = "studentId";
    public static final String FIELD_ENROLLED = "enrolled";

    private static final Comparator<String> BY_NAME =
            Comparator.nullsLast(String.CASE_INSENSITIVE_ORDER);

    /** Two-argument callback used by every asynchronous Firestore call. */
    public interface OnResult<T> {
        void onResult(@Nullable T value, @Nullable Exception error);
    }

    private final CollectionReference students;

    public StudentRepository() {
        students = FirebaseFirestore.getInstance().collection(COLLECTION_STUDENTS);
    }

    /** Creates a new document; the callback receives the generated document ID. */
    public void addStudent(@NonNull String name,
                           @NonNull String studentId,
                           boolean enrolled,
                           @NonNull OnResult<String> callback) {
        Student student = new Student(null, name, studentId, enrolled);
        students.add(student)
                .addOnSuccessListener(reference -> callback.onResult(reference.getId(), null))
                .addOnFailureListener(error -> callback.onResult(null, error));
    }

    /** Overwrites one document with the values taken from the form. */
    public void updateStudent(@NonNull String documentId,
                              @NonNull String name,
                              @NonNull String studentId,
                              boolean enrolled,
                              @NonNull OnResult<Void> callback) {
        Student student = new Student(documentId, name, studentId, enrolled);
        students.document(documentId)
                .set(student)
                .addOnSuccessListener(unused -> callback.onResult(null, null))
                .addOnFailureListener(error -> callback.onResult(null, error));
    }

    /** Removes one document. */
    public void deleteStudent(@NonNull String documentId, @NonNull OnResult<Void> callback) {
        students.document(documentId)
                .delete()
                .addOnSuccessListener(unused -> callback.onResult(null, null))
                .addOnFailureListener(error -> callback.onResult(null, error));
    }

    /** Reads every document once, sorted by student name. */
    public void fetchStudents(@NonNull OnResult<List<Student>> callback) {
        students.get()
                .addOnSuccessListener(snapshot -> callback.onResult(toStudentList(snapshot), null))
                .addOnFailureListener(error -> callback.onResult(null, error));
    }

    /**
     * Checks whether a student ID is already stored.
     *
     * @param excludedDocumentId the record being edited, or null when adding
     */
    public void isStudentIdUsed(@NonNull String studentId,
                                @Nullable String excludedDocumentId,
                                @NonNull OnResult<Boolean> callback) {
        students.whereEqualTo(FIELD_STUDENT_ID, studentId)
                .get()
                .addOnSuccessListener(snapshot -> {
                    boolean used = false;
                    for (QueryDocumentSnapshot document : snapshot) {
                        if (excludedDocumentId == null
                                || !excludedDocumentId.equals(document.getId())) {
                            used = true;
                            break;
                        }
                    }
                    callback.onResult(used, null);
                })
                .addOnFailureListener(error -> callback.onResult(null, error));
    }

    @NonNull
    private List<Student> toStudentList(@NonNull QuerySnapshot snapshot) {
        List<Student> result = new ArrayList<>();
        for (QueryDocumentSnapshot document : snapshot) {
            Student student = document.toObject(Student.class);
            if (student == null) {
                continue;
            }
            student.setDocumentId(document.getId());
            result.add(student);
        }
        Collections.sort(result, (first, second) -> BY_NAME.compare(first.getName(), second.getName()));
        return result;
    }
}
